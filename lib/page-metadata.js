export function pageMetadata(key, path, page = 1) {
  const {title, description, keywords} = pages[key];
  const label = page > 1 ? title + ' | الصفحة ' + page.toLocaleString('ar-SA') : title;
  const fullTitle = label.includes(siteName) ? label : label + ' | ' + siteName;
  const url = absoluteUrl(path);
  const image = absoluteUrl('/icon.png');
  return {
    title: {absolute: fullTitle}, description, keywords, publisher: siteName,
    alternates: {canonical: url},
    openGraph: {type: 'website', locale: 'ar_SA', siteName, title: fullTitle, description, url, images: [{url: image, alt: siteName}]},
    twitter: {card: 'summary', title: fullTitle, description, images: [image]},
    ...(key === 'search' && {robots: {index: false, follow: true}})
  };
}
